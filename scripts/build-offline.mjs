import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";

const dist = new URL("../dist/", import.meta.url);
const template = await readFile(new URL("./sw.template.js", import.meta.url), "utf8");

async function listFiles(folder = "") {
  const entries = await readdir(new URL(folder, dist), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith(".")) continue;
    const path = folder + entry.name;
    if (entry.isDirectory()) files.push(...await listFiles(path + "/"));
    if (entry.isFile() && path !== "sw.js") files.push(path);
  }
  return files;
}

const files = (await listFiles()).sort();
const hash = createHash("sha256").update(template);
for (const file of files) {
  const contents = await readFile(new URL(file, dist));
  hash.update(JSON.stringify([file, contents.length])).update(contents);
}
const revision = hash.digest("hex").slice(0, 16);
const worker = template
  .replace("__MISE_REVISION__", revision)
  .replace("__MISE_ASSET_LIST__", JSON.stringify(files, null, 2));
await writeFile(new URL("sw.js", dist), "// Generated by scripts/build-offline.mjs.\n" + worker);
console.log(`Prepared ${files.length} offline files for Mise (${revision}).`);
